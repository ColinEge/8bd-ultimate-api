package command

import (
	"fmt"
	"testing"
)

func TestPacketToHID(t *testing.T) {
	type test struct {
		Hid    uint32
		Packet []byte
	}

	tests := []test{
		{Hid: 0x04, Packet: []byte{0x07, 0x00, 0x01}},                   // a
		{Hid: 0x05, Packet: []byte{0x07, 0x00, 0x02}},                   // b
		{Hid: 0x06, Packet: []byte{0x07, 0x00, 0x04}},                   // c
		{Hid: 0x07, Packet: []byte{0x07, 0x00, 0x08}},                   // d
		{Hid: 0x08, Packet: []byte{0x07, 0x00, 0x10}},                   // e
		{Hid: 0x09, Packet: []byte{0x07, 0x00, 0x20}},                   // f
		{Hid: 0x0a, Packet: []byte{0x07, 0x00, 0x40}},                   // g
		{Hid: 0x0b, Packet: []byte{0x07, 0x00, 0x80}},                   // h
		{Hid: 0x0c, Packet: []byte{0x07, 0x00, 0x00, 0x01}},             // i
		{Hid: 0x0d, Packet: []byte{0x07, 0x00, 0x00, 0x02}},             // j
		{Hid: 0x0e, Packet: []byte{0x07, 0x00, 0x00, 0x04}},             // k
		{Hid: 0x0f, Packet: []byte{0x07, 0x00, 0x00, 0x08}},             // l
		{Hid: 0x10, Packet: []byte{0x07, 0x00, 0x00, 0x10}},             // m
		{Hid: 0x11, Packet: []byte{0x07, 0x00, 0x00, 0x20}},             // n
		{Hid: 0x12, Packet: []byte{0x07, 0x00, 0x00, 0x40}},             // o
		{Hid: 0x13, Packet: []byte{0x07, 0x00, 0x00, 0x80}},             // p
		{Hid: 0x14, Packet: []byte{0x07, 0x00, 0x00, 0x00, 0x01}},       // q
		{Hid: 0x15, Packet: []byte{0x07, 0x00, 0x00, 0x00, 0x02}},       // r
		{Hid: 0x16, Packet: []byte{0x07, 0x00, 0x00, 0x00, 0x04}},       // s
		{Hid: 0x17, Packet: []byte{0x07, 0x00, 0x00, 0x00, 0x08}},       // t
		{Hid: 0x18, Packet: []byte{0x07, 0x00, 0x00, 0x00, 0x10}},       // u
		{Hid: 0x19, Packet: []byte{0x07, 0x00, 0x00, 0x00, 0x20}},       // v
		{Hid: 0x1a, Packet: []byte{0x07, 0x00, 0x00, 0x00, 0x40}},       // w
		{Hid: 0x1b, Packet: []byte{0x07, 0x00, 0x00, 0x00, 0x80}},       // x
		{Hid: 0x1c, Packet: []byte{0x07, 0x00, 0x00, 0x00, 0x00, 0x01}}, // y
		{Hid: 0x1d, Packet: []byte{0x07, 0x00, 0x00, 0x00, 0x00, 0x02}}, // z
		{Hid: 0x65, Packet: []byte{0x07, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02}},
	}
	for _, test := range tests {
		hid, ok := packetToHID(test.Packet)
		if !ok {
			fmt.Printf("Packet %02x is invalid\n", test.Packet)
		}
		if test.Hid != hid {
			fmt.Printf("Expected Packet %02x → HID usage: %02x\n", test.Hid, hid)
		}
	}
}
